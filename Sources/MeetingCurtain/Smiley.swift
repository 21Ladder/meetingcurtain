    func path(in rect: CGRect) -> Path {
        let side = min(rect.width, rect.height)
        let origin = CGPoint(x: rect.midX - side / 2, y: rect.midY - side / 2)
        func mid(_ a: CGPoint, _ b: CGPoint) -> CGPoint { CGPoint(x: (a.x + b.x) / 2, y: (a.y + b.y) / 2) }

        var path = Path()
        for outline in Self.outlines {
            let points = stride(from: 0, to: outline.count - 1, by: 2).map {
                CGPoint(x: origin.x + outline[$0] * side, y: origin.y + outline[$0 + 1] * side)
            }
            path.move(to: mid(points[points.count - 1], points[0]))
            for i in points.indices {
                path.addQuadCurve(to: mid(points[i], points[(i + 1) % points.count]), control: points[i])
            }
            path.closeSubpath()
        }
        return path
    }

